/** ¿Es una clave del catálogo (y no uno de tus libros)? */
export const delCatalogo = (clave) => String(clave ?? '').startsWith('cat:');

/** El libro del catálogo con esa clave, como los de tu biblioteca (id, title, author, pageCount, publishedDate, isbn, cover). */
const POR_CLAVE = new Map(CATALOGO_LIBROS.map((x) => [x.clave, x]));
export function libroDelCatalogo(clave) {
  const x = POR_CLAVE.get(clave);
  return x ? { id: x.clave, title: x.titulo, author: x.autor, pageCount: x.paginas, publishedDate: String(x.anio ?? ''), isbn: x.isbn, cover: x.cover, genero: x.genero, catalogo: true } : null;
}
